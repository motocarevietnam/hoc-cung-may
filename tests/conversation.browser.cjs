const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
  const url=process.env.MAY_TEST_URL||'http://127.0.0.1:8082';
  assert.match(url,/^http:\/\/(127\.0\.0\.1|localhost):/);
  const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
  try{
    const context=await browser.newContext({viewport:{width:390,height:844},serviceWorkers:'block'});
    await context.addInitScript(()=>{localStorage.setItem('may_pin',JSON.stringify('test-child'));localStorage.setItem('may_autoRead','false');});
    await context.request.post(url+'/api/parent/clear',{headers:{'x-parent-pin':'test-parent'},data:{what:'all'}});
    const page=await context.newPage(), errors=[];
    const choose=async type=>{const b=page.locator(`[data-cc-turn="${type}"]`);if(!await b.isVisible())await page.locator('#ccActions').click();await b.click();};
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto(url,{waitUntil:'domcontentloaded'});
    await page.locator('#ccBox').waitFor();
    await page.waitForFunction(()=>!document.querySelector('[data-cc-turn="recap"]').disabled);
    assert.equal(await page.locator('.cc-quick button').count(),4);
    assert.equal(await page.locator('.today').count(),0);
    await choose('joy');
    await page.waitForFunction(()=>document.querySelector('.cc-history').textContent.includes('Nghe thích quá'));
    const greetings=await page.locator('.cc-history').innerText();
    await page.reload();
    await page.waitForFunction(()=>document.querySelector('.cc-history').textContent.includes('Nghe thích quá'));
    assert.equal(await page.locator('.cc-history').innerText(),greetings);
    await choose('rest');
    await page.locator('[data-cc-turn="resume"]').waitFor();
    assert.equal(await page.locator('.cc-activities').count(),0);
    await page.locator('#ccBox').fill('Đoạn đang gõ vẫn ở đây');
    await page.reload();
    await page.waitForFunction(()=>document.querySelector('#ccBox')?.value==='Đoạn đang gõ vẫn ở đây');
    await page.context().setOffline(true);
    await page.locator('#ccSend').click();
    await page.waitForFunction(()=>document.querySelector('[role="alert"]')?.textContent.includes('mất mạng'));
    assert.equal(await page.locator('#ccBox').inputValue(),'Đoạn đang gõ vẫn ở đây');
    await context.setOffline(false);
    await choose('direct');
    await page.locator('[data-cc-pick="toan"]').click();
    let lostCheckpoint=false;
    await page.route('**/api/companion/checkpoint',async route=>{
      if(!lostCheckpoint){lostCheckpoint=true;await route.abort();}else await route.continue();
    });
    await page.locator('[data-cc-start="quiz"]').click();
    await page.locator('#ccActivity .opt').first().waitFor();
    assert.equal(await page.locator('.cc-with-workspace').count(),1);
    assert.equal(await page.locator('#ccBox').count(),1);
    assert.equal(lostCheckpoint,true);
    await page.locator('#ccActivity .opt').first().click();
    await page.locator('#ccActivity #next').waitFor();
    await page.reload();
    await page.locator('#ccResume').waitFor();
    await page.locator('#ccResume').click();
    await page.locator('#ccActivity .q').waitFor();
    assert.match(await page.locator('#ccActivity .qcard .muted').innerText(),/Câu 2/);
    await page.setViewportSize({width:1024,height:768});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.screenshot({path:process.env.MAY_TEST_SCREENSHOT||'/tmp/may-issue47-ipad.png',fullPage:true});
    await page.locator('#ccExpand').click();
    assert.equal(await page.locator('#ccExpand').getAttribute('aria-pressed'),'true');
    await page.locator('#ccExpand').click();
    await page.locator('#ccReflect').click();
    await page.waitForFunction(()=>!document.querySelector('#ccActivity'));
    await page.locator('#parentBtn').click();
    assert.equal(await page.locator('#clearLocalDraft').count(),0);
    await page.locator('#ppin').fill('test-parent');
    await page.locator('#unlock').click();
    await page.locator('#clearLocalDraft').waitFor();
    await page.locator('#clearLocalDraft').click();
    assert.equal(await page.evaluate(()=>localStorage.getItem('may_companion_draft')),null);
    await context.request.post(url+'/api/parent/settings',{headers:{'x-parent-pin':'test-parent'},data:{nick:'Kem',focus:'',chat_first:false}});
    await page.goto(url,{waitUntil:'domcontentloaded'});
    await page.locator('.labels').waitFor();
    assert.equal(await page.locator('.cc-shell').count(),0);
    await context.request.post(url+'/api/parent/settings',{headers:{'x-parent-pin':'test-parent'},data:{nick:'Kem',focus:'',chat_first:true}});
    assert.deepEqual(errors,[]);
    console.log('PASS browser: four choices, no repeated greeting, rest, draft persistence, offline send, lost checkpoint retry, inline quiz, reload resume, iPad layout, draft deletion and parent fallback');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
